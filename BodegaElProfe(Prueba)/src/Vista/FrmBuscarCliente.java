    private void btnBuscoCliActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscoCliActionPerformed
        if (ProcesosCliente.BuscarClientes(txtClienteABuscar.getText()) != null){
            ProcesosCliente.mostrarClientes(ProcesosCliente.BuscarClientes(txtClienteABuscar.getText()));
        } else{
            JOptionPane.showMessageDialog(null, "Cliente No Encontrado. Ingrese un Cliente Existente.");
        }
    }//GEN-LAST:event_btnBuscoCliActionPerformed
    
